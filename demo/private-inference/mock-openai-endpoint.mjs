// Standalone OpenAI-compatible mock "self-hosted inference endpoint" for the
// private-inference-routing demo. Binds to 127.0.0.1 ONLY (loopback) so it is
// physically impossible for a request that reaches it to have left the host —
// the demo's whole point is "data never leaves the intranet".
//
// It logs every inbound request with a loud banner (proof the gateway routed
// here) and answers a standard /v1/chat/completions (and /v1/models) so the
// newhub relay treats it as a real OpenAI-compatible upstream.
//
// Run:  bun demo/private-inference/mock-openai-endpoint.mjs
// Port: 11434 (override with MOCK_PORT env)

const PORT = Number(process.env.MOCK_PORT || 11434);
let hits = 0;

const server = Bun.serve({
  hostname: '127.0.0.1', // loopback only — no public interface
  port: PORT,
  async fetch(req) {
    const url = new URL(req.url);
    const ts = new Date().toISOString();
    let bodyText = '';
    try {
      bodyText = await req.text();
    } catch {}
    hits += 1;

    console.log('\n========================================================');
    console.log(`[PRIVATE-ENDPOINT HIT #${hits}] ${ts}`);
    console.log(`  ${req.method} ${url.pathname}`);
    console.log(`  from: ${req.headers.get('x-forwarded-for') || 'loopback'}  ua: ${req.headers.get('user-agent') || '-'}`);
    console.log(`  authorization: ${(req.headers.get('authorization') || '').slice(0, 14)}…`);
    if (bodyText) {
      let model = '?';
      try { model = JSON.parse(bodyText).model; } catch {}
      console.log(`  requested model: ${model}`);
      console.log(`  body: ${bodyText.slice(0, 300)}`);
    }
    console.log('========================================================\n');

    if (url.pathname.endsWith('/models')) {
      return Response.json({
        object: 'list',
        data: [{ id: 'qwen2.5-7b-instruct', object: 'model', owned_by: 'private-self-hosted' }],
      });
    }

    // Standard OpenAI chat-completion response.
    const now = Math.floor(Date.now() / 1000);
    return Response.json({
      id: `chatcmpl-private-${hits}`,
      object: 'chat.completion',
      created: now,
      model: 'qwen2.5-7b-instruct',
      choices: [
        {
          index: 0,
          message: {
            role: 'assistant',
            content:
              'This reply was generated by the ON-PREM self-hosted inference endpoint (127.0.0.1). No external LLM provider was contacted; your data never left the intranet.',
          },
          finish_reason: 'stop',
        },
      ],
      usage: { prompt_tokens: 17, completion_tokens: 29, total_tokens: 46 },
    });
  },
});

console.log(`[mock] private self-hosted OpenAI-compatible endpoint listening on http://127.0.0.1:${server.port}`);
console.log('[mock] loopback-only bind — a request arriving here provably did not egress the host.');
